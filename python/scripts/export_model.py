"""Export the trained statistical model as float32 C constants."""

import hashlib
import json
import math
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT.parent


def float32(value):
    result = struct.unpack("<f", struct.pack("<f", value))[0]
    if not math.isfinite(result):
        raise ValueError("Model value cannot be represented as finite float32")
    return result


def c_float(value):
    return f"{float32(value):.9e}f"


def main():
    model_path = ROOT / "models" / "anomaly_model.json"
    model_bytes = model_path.read_bytes()
    model = json.loads(model_bytes)

    expected = ["temperature_c", "vibration_rms_g", "current_rms_a"]
    if model["schema_version"] != 1:
        raise ValueError("Unsupported model schema")
    if model["model_type"] != "diagonal_standardized_squared_distance":
        raise ValueError("Unsupported model type")
    if model["feature_order"] != expected:
        raise ValueError("Unexpected feature order")

    means = model["means"]
    deviations = model["standard_deviations"]
    threshold = model["threshold"]

    if len(means) != 3 or len(deviations) != 3:
        raise ValueError("Expected three features")
    if not all(math.isfinite(value) for value in means):
        raise ValueError("Invalid means")
    if not all(math.isfinite(value) and value > 0 for value in deviations):
        raise ValueError("Invalid deviations")
    if not math.isfinite(threshold) or threshold < 0:
        raise ValueError("Invalid threshold")
    if not all(float32(value) > 0 for value in deviations):
        raise ValueError("Standard deviation underflow")

    source = model.get("source", "unspecified data")
    if not isinstance(source, str) or any(c in source for c in ("\n", "\r")) or "*/" in source:
        raise ValueError("Invalid model source description")
    digest = hashlib.sha256(model_bytes).hexdigest()
    output = (
        PROJECT / "firmware" / "components" / "anomaly_detector"
        / "include" / "anomaly_model.h"
    )
    output.parent.mkdir(parents=True, exist_ok=True)

    content = f"""#ifndef INDUSTRIAL_ANOMALY_MODEL_H
#define INDUSTRIAL_ANOMALY_MODEL_H

/*
 * Generated by python/scripts/export_model.py.
 * Source: {source}.
 * Feature order: temperature_c, vibration_rms_g, current_rms_a.
 * Score: mean of squared standardized feature values.
 * Decision: score strictly greater than threshold.
 * Regenerate this file when the model changes.
 */
#define ANOMALY_MODEL_FEATURE_COUNT 3U
#define ANOMALY_MODEL_SHA256 "{digest}"
#define ANOMALY_MODEL_THRESHOLD {c_float(threshold)}

static const float anomaly_model_means[ANOMALY_MODEL_FEATURE_COUNT] = {{
    {", ".join(c_float(value) for value in means)}
}};

static const float anomaly_model_stddevs[ANOMALY_MODEL_FEATURE_COUNT] = {{
    {", ".join(c_float(value) for value in deviations)}
}};

#endif /* INDUSTRIAL_ANOMALY_MODEL_H */
"""
    output.write_text(content, encoding="utf-8")
    print("Exported: firmware/components/anomaly_detector/include/anomaly_model.h")
    print(f"Model SHA256: {digest}")
    print(f"Firmware float32 threshold: {float32(threshold):.9f}")
    print("Feature order: temperature_c, vibration_rms_g, current_rms_a")
    print("Model export complete.")


if __name__ == "__main__":
    main()
